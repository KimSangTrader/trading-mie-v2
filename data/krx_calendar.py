from datetime import date
from functools import lru_cache

import pandas_market_calendars as mcal

_XKRX = mcal.get_calendar("XKRX")


@lru_cache(maxsize=8)
def _trading_days_for_year(year: int) -> frozenset:
    """해당 연도의 KRX 실제 거래일 집합을 계산해 캐시한다 - main.py 상시 루프가
    60초마다 호출하므로(_should_run_now 경유) 캐시가 없으면 낭비가 크다."""
    sched = _XKRX.schedule(start_date=f"{year}-01-01", end_date=f"{year}-12-31")
    return frozenset(ts.date() for ts in sched.index)


def is_krx_trading_day(d: date) -> bool:
    """d가 KRX(한국거래소) 실제 거래일이면 True.

    주말은 물론, 설날/추석/근로자의날/대체공휴일/KRX 자체 휴장일(12/31) 등
    XKRX 캘린더가 아는 모든 휴장 사유를 포함해 False를 반환한다."""
    return d in _trading_days_for_year(d.year)
